import assert from 'node:assert/strict';
import {emptyKnowledge,confirmFact,confirmedClarifications,unresolvedQuestions,retractFact,stableId} from '../src/lib/applicationStudio/knowledge.mjs';
const vacancy='English proficiency required.',question='What is your English level?',answer='My English is B2.';
let kb=confirmFact(emptyKnowledge(),{text:answer,kind:'languages',question,vacancyKey:stableId('vacancy',vacancy)});
let resolved=confirmedClarifications(kb,vacancy);
assert.equal(resolved[0].answer,answer);
assert.deepEqual(unresolvedQuestions(['WHAT is your English level !','Do you hold an English certificate?'],resolved),['Do you hold an English certificate?']);
assert.equal(confirmedClarifications(kb,'Another vacancy').length,0);
const restored=JSON.parse(JSON.stringify(kb));
assert.equal(confirmedClarifications(restored,vacancy).length,1);
assert.equal(confirmedClarifications(retractFact(restored,resolved[0].evidenceId),vacancy).length,0);
const legacy=confirmFact(emptyKnowledge(),{text:answer,kind:'languages'});
assert.equal(confirmedClarifications(legacy,vacancy,{a:{question,answer}}).length,1);
assert.equal(confirmedClarifications(emptyKnowledge(),vacancy,{a:{question,answer}}).length,0,'Client answers cannot create evidence');
assert.equal(confirmedClarifications(legacy,vacancy,{a:{question,answer:'I have a certificate'}}).length,0);
kb=confirmFact(kb,{text:answer,kind:'languages',question:'Do you use English at work?',vacancyKey:stableId('vacancy',vacancy)});
assert.equal(confirmedClarifications(kb,vacancy).length,2,'One fact can answer separate questions');
assert.throws(()=>confirmFact(kb,{text:answer,question:'x'.repeat(2001)}),/Invalid confirmation question/);
console.log('Clarifications PASS: persistence, negative answers, source-backed migration, retraction, vacancy scope and distinct follow-ups.');
