function mapStage(stage: CareerJourneyStage, index: number): CareerJourneyStage {
  const spec = stages[index] ?? stages[stages.length - 1];
  return {
    ...stage,
    id: `eaic-stage-${index + 1}`,
    title: spec.title,
    label: spec.title,
    landmark: spec.landmark,
    theme: spec.summary,
    summary: spec.summary,
    explanation: `${spec.summary} The output must be decision-ready, traceable to evidence, explicit about assumptions, and usable by enterprise stakeholders across business, technology, finance, security, risk, legal, HR, and operations.`,
    lessons: [...spec.lessons],
    resources: [...spec.resources],
    tasks: spec.lessons.map((lesson, taskIndex) => ({
      id: `eaic-stage-${index + 1}-task-${taskIndex + 1}`,
      title: `${lesson} advisory artifact`,
      description: `Create a reviewable enterprise consulting artifact for ${lesson.toLowerCase()} with evidence, assumptions, alternatives, risks, owners, and decision criteria.`,
      type: index === 9 ? "career" : index === 8 ? "portfolio" : index >= 7 ? "project" : "lesson",
    })),
    topicAssessments: stage.topicAssessments?.map((assessment, assessmentIndex) => ({
      ...assessment,
      id: `eaic-stage-${index + 1}-topic-${assessmentIndex + 1}`,
      title: `${spec.lessons[assessmentIndex % spec.lessons.length]} knowledge check`,
      topicLabel: spec.lessons[assessmentIndex % spec.lessons.length],
    })),
    phaseExam: stage.phaseExam ? {
      ...stage.phaseExam,
      id: `eaic-stage-${index + 1}-comprehensive-assessment`,
      title: `${spec.title} comprehensive assessment`,
      description: `Scenario assessment covering ${spec.lessons.join(", ")}.`,
    } : undefined,
  };
}

function mapRoadmap(phase: CareerRoadmapPhase, index: number): CareerRoadmapPhase {
  const spec = roadmap[index] ?? roadmap[roadmap.length - 1];
  return {
    ...phase,
    id: `eaic-roadmap-${index + 1}`,
    phaseNumber: index + 1,
    title: spec[0],
    goal: `Build decision-ready enterprise consulting competence across ${spec.slice(1).join(", ")}.`,
    sections: spec.slice(1),
    mentorTip: index === 0
      ? "Enterprise AI consulting is not a technology shopping exercise. Start from strategy, operating constraints, evidence, accountability, and measurable outcomes."
      : index === 3
        ? "Governance should change with risk. Avoid one process for every use case; define proportional controls and explicit escalation paths."
        : "Make every recommendation traceable to alternatives, evidence, economics, risk, ownership, and the conditions that would change the decision.",
    practicalMissions: [
      `Produce one executive-ready artifact for ${spec[1]}.`,
      `Defend a recommendation spanning ${spec.slice(2, 5).join(", ")}.`,
    ],
    expectedOutcome: `You can explain, design, and defend ${spec[0].toLowerCase()} at enterprise scope.`,
    quiz: { ...phase.quiz, id: `eaic-roadmap-${index + 1}-quiz`, phaseId: `eaic-roadmap-${index + 1}`, title: `${spec[0]} checkpoint` },
    lessons: phase.lessons.map((lesson, lessonIndex) => ({
      ...lesson,
      id: `eaic-roadmap-${index + 1}-lesson-${lessonIndex + 1}`,
      title: `${spec[1 + (lessonIndex % (spec.length - 1))]} consulting practice`,
      summary: `Apply ${spec[1 + (lessonIndex % (spec.length - 1))]} to a multi-stakeholder enterprise AI decision.`,
      mission: `Create evidence and a decision artifact for ${spec[1 + (lessonIndex % (spec.length - 1))]}.`,
      resources: [...(stages[Math.min(index * 2 + Math.floor(lessonIndex / 2), stages.length - 1)]?.resources ?? stages[0].resources)],
    })),
  };
}

