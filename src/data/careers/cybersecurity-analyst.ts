function q(
  id: string,
  question: string,
  answers: string[],
  correctAnswerIndex: number,
  explanation: string,
  relatedTopic: string,
  difficulty: WorkspaceDifficulty = "Intermediate",
): CareerQuizQuestion {
  return {
    id,
    question,
    answers,
    correctAnswerIndex,
    explanation,
    difficulty,
    relatedTopic,
    questionType: question.toLowerCase().includes("scenario") ? "scenario" : "multiple-choice",
    status: "active",
    lastReviewedAt: "2026-08-02",
    version: 1,
  };
}

function topicAssessment(
  id: string,
  title: string,
  topicLabel: string,
  questions: CareerQuizQuestion[],
): CareerAssessment {
  return {
    id,
    title,
    description: `A role-specific knowledge check for ${topicLabel}.`,
    passingScore: 70,
    assessmentType: "topic",
    topicId: id,
    topicLabel,
    durationMinutes: 12,
    questionsPerAttempt: questions.length,
    questions,
  };
}

function lesson(
  id: string,
  title: string,
  summary: string,
  outcomes: string[],
  mission: string,
  lessonResources: CareerResource[],
  difficulty: WorkspaceDifficulty = "Intermediate",
): CareerLesson {
  return {
    id,
    title,
    summary,
    estimatedTime: "3-5 hours",
    difficulty,
    outcomes,
    resources: lessonResources,
    mission,
  };
}

